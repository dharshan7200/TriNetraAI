"""Placeholder study data: 120 SIMULATED journeys in the layout of the real study.

Use it to run the complete study pipeline (fit, E1, E2, E3) end to end before the physical
journeys exist. It lives in its own folder (default ``data/placeholder/``), every journey code
starts with ``PLACEHOLDER-``, every file is flagged synthetic, and every output is watermarked.
Replace it with the captured journeys at the real paths before reporting anything.
"""

from __future__ import annotations

import json
import shutil
from pathlib import Path
from typing import Any, Dict

from trinetra_link.config import REPO_ROOT
from trinetra_link.sim.simulator import SimConfig, simulate_benchmark
from trinetra_link.staging.split import CALIBRATION_QUOTAS

DEFAULT_PLACEHOLDER_DIR = REPO_ROOT / "data" / "placeholder"
PLACEHOLDER_WATERMARK = "PLACEHOLDER — SIMULATED JOURNEYS, NOT PHYSICAL DATA — REPLACE BEFORE REPORTING"

# File names mirror the real study layout (data/trinetra_store.sqlite, data/derived/split_manifest.json,
# data/restricted/staging_log_120.csv, data/derived/scales.json) so the same commands run on both.
FILES = {
    "store.db": "trinetra_store.sqlite",
    "staging_log.csv": "staging_log_120.csv",
    "split_manifest.json": "split_manifest.json",
    "scales.json": "scales.json",
}


def create_placeholder_dataset(output_dir: Path | str | None = None, seed: int = 120) -> Dict[str, Any]:
    out = Path(output_dir) if output_dir else DEFAULT_PLACEHOLDER_DIR
    if out.exists():
        shutil.rmtree(out)
    info = simulate_benchmark(out, SimConfig(seed=seed, cell_multiplier=1), code_prefix="PLACEHOLDER",
                              calibration_quotas=CALIBRATION_QUOTAS)
    for src, dst in FILES.items():
        (out / src).rename(out / dst)
    for name in ("split_manifest.json", "scales.json"):
        path = out / name
        data = json.loads(path.read_text())
        data.update({"synthetic": True, "placeholder": True, "watermark": PLACEHOLDER_WATERMARK})
        path.write_text(json.dumps(data, indent=1))
    # QUARANTINE.md is the marker the repository's anti-fabrication guards use to exclude generated data.
    (out / "QUARANTINE.md").write_text(
        f"# {PLACEHOLDER_WATERMARK}\n\nGenerated by `trinetra placeholder create`; quarantined from the data guards.\n"
    )
    (out / "README_PLACEHOLDER.txt").write_text(
        PLACEHOLDER_WATERMARK + "\n\n"
        "120 simulated journeys (24 calibration / 96 test, protocol cell quotas) generated by\n"
        "trinetra_link.sim.placeholder. They exist only so the full pipeline can be run before the\n"
        "physical study. Never report numbers computed from them as results.\n"
    )
    return {**info, "output_dir": str(out), **{k: str(out / v) for k, v in
            (("db", FILES["store.db"]), ("staging_log", FILES["staging_log.csv"]),
             ("manifest", FILES["split_manifest.json"]), ("scales", FILES["scales.json"]))}}
